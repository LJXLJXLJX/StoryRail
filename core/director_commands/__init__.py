def __getattr__(name: str):
    if name != "DirectorCommandRegistry":
        raise AttributeError(f"module {__name__!r} has no attribute {name!r}")
    from .registry import DirectorCommandRegistry

    globals()[name] = DirectorCommandRegistry
    return DirectorCommandRegistry


def __dir__() -> list[str]:
    return sorted({*globals(), *__all__})


